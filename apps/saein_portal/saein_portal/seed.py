def run():
    for domain, metrics in METRICS.items():
        for title, unit, direction, definition in metrics:
            if not frappe.db.exists("Portal Metric",{"domain":domain,"title":title}):
                d={"doctype":"Portal Metric","domain":domain,"title":title,"definition":definition,"formula":definition,"unit":unit,"direction":direction,"source":"ورود دستی؛ اتصال زنده تنظیم نشده است","frequency":"Quarterly" if "فصلی" in title else "Monthly"}
                if title == "دسترس‌پذیری سرویس": d.update(has_default_target=1,default_target=99)
                frappe.get_doc(d).insert()
    for domain, titles in WEEKLY.items():
        for day,title in enumerate(titles):
            if not frappe.db.exists("Portal Template",{"domain":domain,"title":title}):
                frappe.get_doc({"doctype":"Portal Template","domain":domain,"title":title,"frequency":"Weekly","weekday":(day+5)%7,"enabled":0}).insert()
    for domain, titles in MONTHLY.items():
        for week,title in enumerate(titles):
            if not frappe.db.exists("Portal Template",{"domain":domain,"title":title}):
                frappe.get_doc({"doctype":"Portal Template","domain":domain,"title":title,"frequency":"Monthly","day_of_month":week*7+1,"enabled":0}).insert()
    for key,title in [("stagnation","تعریف رسوب"),("coverage","پوشش مجاز"),("dormant_customer","مشتری راکد"),("churn","ریزش مشتری"),("visit_attribution","مهلت انتساب فروش به بازدید")]:
        if not frappe.db.exists("Portal Policy",key):
            frappe.get_doc({"doctype":"Portal Policy","policy_key":key,"title":title,"configured":0}).insert()
    return {"metrics":frappe.db.count("Portal Metric"),"templates":frappe.db.count("Portal Template")}
